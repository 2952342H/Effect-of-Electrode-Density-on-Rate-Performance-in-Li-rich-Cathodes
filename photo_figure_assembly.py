"""Figure 3.5.1"""

from io import BytesIO

from google.colab import files
from IPython.display import display
from matplotlib import font_manager
from PIL import Image, ImageDraw, ImageFont, ImageOps

# Panels in order from left to right.
order = [
    "Assembly of the Li-rich cathode–lithium metal coin cell.png",  # (A)
    "S__77881355_0.jpg",  # (B) Electrolyte
    "S__77881365_0.jpg",  # (C) Crimper
    "S__77881385_0.jpg",  # (D) Assembled cell
]

uploaded = files.upload()
missing = [name for name in order if name not in uploaded]
if missing:
    raise ValueError("Missing source file(s): " + ", ".join(missing))

panels = []
for name in order:
    with Image.open(BytesIO(uploaded[name])) as source:
        panels.append(ImageOps.exif_transpose(source).convert("RGB"))

# Match panel heights while preserving the original aspect ratios.
dpi = 300
width = round(16 / 2.54 * dpi)
margin, gap, label_band = 18, 34, 82
available_width = width - 2 * margin - 3 * gap
ratios = [panel.width / panel.height for panel in panels]
panel_height = int(available_width / sum(ratios))
panel_widths = [int(panel_height * ratio) for ratio in ratios]
x = (width - sum(panel_widths) - 3 * gap) // 2

font_path = font_manager.findfont(font_manager.FontProperties(
    family=["Times New Roman", "Liberation Serif", "DejaVu Serif"]
))
font = ImageFont.truetype(font_path, round(12 * dpi / 72))
figure = Image.new("RGB", (width, 2 * margin + panel_height + label_band), "white")
draw = ImageDraw.Draw(figure)

for label, panel, panel_width in zip("ABCD", panels, panel_widths):
    resized = panel.resize((panel_width, panel_height), Image.Resampling.LANCZOS)
    figure.paste(resized, (x, margin))
    draw.text(
        (x + panel_width // 2, margin + panel_height + label_band // 2),
        f"({label})", font=font, fill="black", anchor="mm",
    )
    x += panel_width + gap

# Save in the Colab session and display the figure.
figure.save("Figure_3.5.1.png", dpi=(dpi, dpi))
display(figure)

